const normalizeText = (text) => {
  return String(text).replace(/\s+/g, ' ').trim();
};

const getFirstMatch = (text, regex) => {
  const match = text.match(regex);
  return match ? match[1] : null;
};

function translateBackendTextByPattern(text, language) {
  if (language !== 'en') return null;

  const rsiValue = getFirstMatch(text, /^RSI\s+([\d.,]+)\s+nằm trong vùng khỏe$/);
  if (rsiValue) {
    return `RSI ${rsiValue} is in a healthy range.`;
  }

  const rsiAverageValue = getFirstMatch(text, /^RSI\s+([\d.,]+)\s+ở vùng trung bình, cần theo dõi thêm$/);
  if (rsiAverageValue) {
    return `RSI ${rsiAverageValue} is in the average zone and should be monitored further.`;
  }

  const rsiHighValue = getFirstMatch(text, /^RSI\s+([\d.,]+)\s+hơi cao, hạn chế mua đuổi$/);
  if (rsiHighValue) {
    return `RSI ${rsiHighValue} is relatively high, avoid chasing the price.`;
  }

  const rsiOverboughtValue = getFirstMatch(text, /^RSI\s+([\d.,]+)\s+trên 70, có rủi ro quá mua$/);
  if (rsiOverboughtValue) {
    return `RSI ${rsiOverboughtValue} is above 70, indicating overbought risk.`;
  }

  const rsiWeakValue = getFirstMatch(text, /^RSI\s+([\d.,]+)\s+dưới 40, lực giá còn yếu$/);
  if (rsiWeakValue) {
    return `RSI ${rsiWeakValue} is below 40, showing weak price momentum.`;
  }

  const rsiOversoldValue = getFirstMatch(text, /^RSI\s+([\d.,]+)\s+dưới 30, quá bán nhưng chưa nên mua nếu chưa có tín hiệu hồi$/);
  if (rsiOversoldValue) {
    return `RSI ${rsiOversoldValue} is below 30, but buying should be avoided until a recovery signal appears.`;
  }

  const riskRewardGood = getFirstMatch(text, /^Risk\/Reward khoảng\s+([\d.,]+), tương đối hấp dẫn$/);
  if (riskRewardGood) {
    return `Risk/Reward is around ${riskRewardGood}, which is relatively attractive.`;
  }

  const riskRewardAcceptable = getFirstMatch(text, /^Risk\/Reward khoảng\s+([\d.,]+), tạm chấp nhận$/);
  if (riskRewardAcceptable) {
    return `Risk/Reward is around ${riskRewardAcceptable}, which is acceptable.`;
  }

  const missingStockDataSymbol = getFirstMatch(text, /^Không tìm thấy dữ liệu giao dịch cho mã:\s*([A-Z0-9._-]+)$/);
  if (missingStockDataSymbol) {
    return `No trading data found for symbol: ${missingStockDataSymbol}`;
  }

  const tooLittleDataSymbol = getFirstMatch(text, /^Dữ liệu cho mã\s+([A-Z0-9._-]+)\s+quá ít để phân tích kỹ thuật$/);
  if (tooLittleDataSymbol) {
    return `Not enough data for symbol ${tooLittleDataSymbol} to perform technical analysis.`;
  }

  const notEnoughPriceSymbol = getFirstMatch(text, /^Không đủ dữ liệu giá để phân tích mã\s+([A-Z0-9._-]+)$/);
  if (notEnoughPriceSymbol) {
    return `Not enough price data to analyze symbol ${notEnoughPriceSymbol}.`;
  }

  const noExportDataSymbol = getFirstMatch(text, /^Không có dữ liệu lịch sử để xuất file cho mã\s+([A-Z0-9._-]+)$/);
  if (noExportDataSymbol) {
    return `No historical data is available to export for symbol ${noExportDataSymbol}.`;
  }

  const backendSystemError = getFirstMatch(text, /^Lỗi hệ thống Máy chủ Backend:\s*(.+)$/);
  if (backendSystemError) {
    return `Backend server error: ${backendSystemError}`;
  }

  const exportSystemError = getFirstMatch(text, /^Lỗi xuất tệp Excel hệ thống:\s*(.+)$/);
  if (exportSystemError) {
    return `Excel export system error: ${exportSystemError}`;
  }

  return null;
}

export function translateBackendText(text, language) {
  if (text === null || text === undefined || text === '') return text;
  if (language === 'vi') return text;

  const normalizedText = normalizeText(text);
  const dictionary = backendTextTranslations[language] || {};
  const exactTranslation = dictionary[normalizedText];

  if (exactTranslation) {
    return exactTranslation;
  }

  return translateBackendTextByPattern(normalizedText, language) || text;
}

export function translateBackendTextList(items, language) {
  if (!Array.isArray(items)) return [];
  return items.map((item) => translateBackendText(item, language));
}

export function translateActionCode(code, language) {
  if (code === null || code === undefined || code === '') return code;

  const normalizedCode = normalizeText(code);
  const dictionary = actionCodeTranslations[language] || actionCodeTranslations.en;

  return dictionary[normalizedCode] || normalizedCode;
}
